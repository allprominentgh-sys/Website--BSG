
import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@supabase/supabase-js";
import {
  createHmac,
  timingSafeEqual,
} from "crypto";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const COOKIE_NAME = "bsg_admin_session";

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
const sessionSecret = process.env.ADMIN_SESSION_SECRET;

function jsonError(message: string, status: number) {
  return NextResponse.json({ error: message }, { status });
}

/**
 * IMPORTANT:
 * Match this validator to the exact token format generated by
 * your existing /api/admin/login route before deployment.
 *
 * Expected format here: base64url(payload).hexHmacSignature
 * where payload is JSON containing email and exp.
 */
function validateAdminSession(request: NextRequest): boolean {
  if (!sessionSecret) return false;

  const token = request.cookies.get(COOKIE_NAME)?.value;
  if (!token) return false;

  const parts = token.split(".");
  if (parts.length !== 2) return false;

  const [payload, suppliedSignature] = parts;
  if (!payload || !suppliedSignature) return false;

  const expectedSignature = createHmac("sha256", sessionSecret)
    .update(payload)
    .digest("hex");

  const supplied = Buffer.from(suppliedSignature, "hex");
  const expected = Buffer.from(expectedSignature, "hex");

  if (
    supplied.length !== expected.length ||
    !timingSafeEqual(supplied, expected)
  ) {
    return false;
  }

  try {
    const decoded = JSON.parse(
      Buffer.from(payload, "base64url").toString("utf8")
    );

    return (
      decoded.email === "admin@bestsalesgh.com" &&
      typeof decoded.exp === "number" &&
      decoded.exp > Math.floor(Date.now() / 1000)
    );
  } catch {
    return false;
  }
}

function getSupabase() {
  if (!supabaseUrl || !serviceRoleKey) {
    throw new Error("Missing Supabase server environment variables.");
  }

  return createClient(supabaseUrl, serviceRoleKey, {
    auth: {
      autoRefreshToken: false,
      persistSession: false,
    },
  });
}

function requireAdmin(request: NextRequest) {
  if (!validateAdminSession(request)) {
    return jsonError("Unauthorized. Central admin login required.", 401);
  }

  return null;
}

// GET: List payment records.
export async function GET(request: NextRequest) {
  const authError = requireAdmin(request);
  if (authError) return authError;

  try {
    const supabase = getSupabase();
    const { searchParams } = new URL(request.url);

    const status = searchParams.get("status");
    const orderId = searchParams.get("order_id");
    const page = Math.max(
      1,
      Number.parseInt(searchParams.get("page") || "1", 10) || 1
    );
    const pageSize = Math.min(
      100,
      Math.max(
        1,
        Number.parseInt(searchParams.get("pageSize") || "50", 10) || 50
      )
    );

    let query = supabase
      .from("order_payment_records")
      .select("*", { count: "exact" })
      .order("created_at", { ascending: false });

    if (
      status &&
      ["PENDING", "CONFIRMED", "REJECTED", "REFUNDED"].includes(status)
    ) {
      query = query.eq("payment_status", status);
    }

    if (orderId) {
      query = query.eq("order_id", orderId);
    }

    const from = (page - 1) * pageSize;
    const to = from + pageSize - 1;

    const { data, error, count } = await query.range(from, to);

    if (error) {
      console.error("Payment records GET error:", error.message);
      return jsonError("Unable to retrieve payment records.", 500);
    }

    return NextResponse.json({
      payments: data ?? [],
      pagination: {
        page,
        pageSize,
        total: count ?? 0,
        totalPages: Math.ceil((count ?? 0) / pageSize),
      },
    });
  } catch (error) {
    console.error("Payment records GET failure:", error);
    return jsonError("Server error retrieving payment records.", 500);
  }
}

// POST: Record a payment as PENDING.
// This does not verify receipt of money.
export async function POST(request: NextRequest) {
  const authError = requireAdmin(request);
  if (authError) return authError;

  try {
    const body = await request.json();

    const orderId =
      typeof body.order_id === "string" ? body.order_id.trim() : "";
    const amount = Number(body.amount);
    const currencyCode =
      typeof body.currency_code === "string"
        ? body.currency_code.trim().toUpperCase()
        : "GHS";
    const paymentMethod =
      typeof body.payment_method === "string"
        ? body.payment_method.trim()
        : "MANUAL";
    const paymentReference =
      typeof body.payment_reference === "string"
        ? body.payment_reference.trim()
        : null;
    const notes =
      typeof body.notes === "string" ? body.notes.trim() : null;

    if (!orderId) {
      return jsonError("order_id is required.", 400);
    }

    if (!Number.isFinite(amount) || amount <= 0) {
      return jsonError("amount must be greater than zero.", 400);
    }

    if (!/^[A-Z]{3}$/.test(currencyCode)) {
      return jsonError("currency_code must be a 3-letter currency code.", 400);
    }

    if (!paymentMethod || paymentMethod.length > 50) {
      return jsonError("Invalid payment_method.", 400);
    }

    if (paymentReference && paymentReference.length > 200) {
      return jsonError("Payment reference is too long.", 400);
    }

    const supabase = getSupabase();

    const { data: order, error: orderError } = await supabase
      .from("orders")
      .select("id")
      .eq("id", orderId)
      .maybeSingle();

    if (orderError) {
      console.error("Order lookup error:", orderError.message);
      return jsonError("Unable to verify the order.", 500);
    }

    if (!order) {
      return jsonError("Order not found.", 404);
    }

    const { data: payment, error } = await supabase
      .from("order_payment_records")
      .insert({
        order_id: orderId,
        amount: Number(amount.toFixed(2)),
        currency_code: currencyCode,
        payment_method: paymentMethod,
        payment_reference: paymentReference || null,
        payment_status: "PENDING",
        notes: notes || null,
      })
      .select("*")
      .single();

    if (error) {
      console.error("Payment record insert error:", error.message);

      if (error.code === "23505") {
        return jsonError(
          "That payment reference already exists.",
          409
        );
      }

      return jsonError("Unable to create payment record.", 500);
    }

    return NextResponse.json(
      {
        message: "Payment recorded as pending verification.",
        payment,
      },
      { status: 201 }
    );
  } catch (error) {
    console.error("Payment record POST failure:", error);
    return jsonError("Invalid request or server error.", 500);
  }
}

// PATCH: Confirm or reject a pending payment.
// Only the central admin session may reach this handler.
export async function PATCH(request: NextRequest) {
  const authError = requireAdmin(request);
  if (authError) return authError;

  try {
    const body = await request.json();

    const paymentId =
      typeof body.payment_id === "string" ? body.payment_id.trim() : "";
    const action =
      typeof body.action === "string" ? body.action.trim().toUpperCase() : "";
    const notes =
      typeof body.notes === "string" ? body.notes.trim() : null;

    if (!paymentId) {
      return jsonError("payment_id is required.", 400);
    }

    if (!["CONFIRMED", "REJECTED"].includes(action)) {
      return jsonError(
        "action must be CONFIRMED or REJECTED.",
        400
      );
    }

    const supabase = getSupabase();

    // Resolve the central admin's Auth UUID for the verification audit.
    const { data: usersResult, error: usersError } =
      await supabase.auth.admin.listUsers({ page: 1, perPage: 1000 });

    if (usersError) {
      console.error("Admin identity lookup error:", usersError.message);
      return jsonError("Unable to verify admin identity.", 500);
    }

    const adminUser = usersResult.users.find(
      (user) =>
        user.email?.toLowerCase() === "admin@bestsalesgh.com"
    );

    if (!adminUser) {
      return jsonError(
        "Central admin Auth user was not found.",
        500
      );
    }

    const { data: existing, error: lookupError } = await supabase
      .from("order_payment_records")
      .select("id,payment_status")
      .eq("id", paymentId)
      .maybeSingle();

    if (lookupError) {
      console.error("Payment lookup error:", lookupError.message);
      return jsonError("Unable to find payment record.", 500);
    }

    if (!existing) {
      return jsonError("Payment record not found.", 404);
    }

    if (existing.payment_status !== "PENDING") {
      return jsonError(
        "Only pending payments can be confirmed or rejected.",
        409
      );
    }

    const updateData: Record<string, unknown> = {
      payment_status: action,
      verified_by: adminUser.id,
      verified_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };

    if (notes) updateData.notes = notes;

    const { data: payment, error: updateError } = await supabase
      .from("order_payment_records")
      .update(updateData)
      .eq("id", paymentId)
      .eq("payment_status", "PENDING")
      .select("*")
      .maybeSingle();

    if (updateError) {
      console.error("Payment verification error:", updateError.message);
      return jsonError("Unable to update payment status.", 500);
    }

    if (!payment) {
      return jsonError(
        "Payment status changed already. Refresh and try again.",
        409
      );
    }

    return NextResponse.json({
      message:
        action === "CONFIRMED"
          ? "Payment marked as confirmed by the central admin."
          : "Payment rejected by the central admin.",
      payment,
      moneyTransferred: false,
      companyAccountDebited: false,
    });
  } catch (error) {
    console.error("Payment verification failure:", error);
    return jsonError("Invalid request or server error.", 500);
  }
}
